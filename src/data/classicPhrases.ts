const feedbackAuthors: ClassicId[] = [
  'pushkin',
  'tolstoy',
  'dostoevsky',
  'gogol',
  'chekhov',
  'mayakovsky',
  'bulgakov'
];

export function createClassicFeedback(charCount: number): ClassicFeedback {
  const bucket = getTextLengthBucket(charCount);
  const classicId = pickRandom(feedbackAuthors);
  const text = pickRandom(phraseBank[classicId][bucket]);

  return {
    id: crypto.randomUUID(),
    classicId,
    classicName: classicNames[classicId],
    text,
    createdAt: new Date().toISOString()
  };
}
